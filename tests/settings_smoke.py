from playwright.sync_api import expect


def settings_smoke(browser, app, origin, browser_page):
    with browser_page(browser, origin, viewport={"width": 1440, "height": 900}) as page:
        report = app.connection_info()
        pinecone = report["providers"]["pinecone"]
        pinecone.update(status="connected", can_test=True, index_state="Ready")
        tests = []

        def update_connections(route):
            if route.request.url.endswith("/test"):
                assert route.request.post_data_json == {"provider": "pinecone"}
                tests.append(route)
                return
            route.fulfill(json=report)

        page.route("**/api/connections/*", update_connections)
        assert page.goto("/").ok
        page.locator('.sidebar [data-view="chat"]').click()
        expect(page.locator("#chat-view")).to_be_visible()
        page.evaluate("location.hash = '#settings/connections/configured'")
        disclosure = page.locator('[data-settings="connections"]')
        expect(disclosure).to_be_focused()
        expect(disclosure).to_have_attribute("aria-expanded", "true")
        expect(page.locator("#configured-tab")).to_have_attribute("aria-selected", "true")
        field = page.locator("#connection-pinecone")
        field.fill("fixture-index")
        provider_search = page.locator('#configured-panel input[type="search"]')
        provider_search.fill("no matches")
        expect(field).to_have_count(0)
        provider_search.clear()
        expect(field).to_have_value("fixture-index")
        test = page.locator("#test-connection-pinecone")
        test.click()
        expect(page.locator("#connection-notice")).to_have_text("Testing Pinecone…")
        expect(field).to_be_disabled()
        expect(test).to_be_disabled()
        configured = page.locator("#configured-tab")
        configured.press("ArrowRight")
        expect(page.locator("#not-configured-tab")).to_be_focused()
        page.go_back()
        expect(configured).to_have_attribute("aria-selected", "true")
        expect(field).to_have_value("fixture-index")
        expect(test).to_be_disabled()
        pinecone.update(test_status="passed", test_detail="Fixture authorized")
        tests.pop().fulfill(json=report)
        expect(test).to_be_enabled()
        expect(page.locator("#connection-notice")).to_have_text("Pinecone · Fixture authorized")

        page.locator('[data-settings="brain"]').click()
        expect(page.locator("#brain-save")).to_be_enabled()
        page.locator("#routing-prompt").fill("Remind me to check the oven")
        page.locator("#routing-test").click()
        expect(page.locator("#routing-result")).to_be_visible()
        page.locator("#brain-test").click()
        expect(page.locator("#brain-test-reply")).not_to_be_empty()
        page.locator("#brain-workers").select_option("3")
        page.locator("#brain-save").click()
        expect(page.locator("#brain-feedback")).to_have_text("Brain settings saved.")

        page.locator('[data-settings="memory"]').click()
        expect(page.locator("#memory-fields")).to_be_enabled()
        page.locator("#memory-top-k").fill("7")
        page.locator('#memory-settings-form button[type="submit"]').click()
        expect(page.locator("#memory-feedback")).to_have_text("Settings saved.")
        expect(page.locator("#memory-top-k")).to_have_value("7")
        page.locator('[data-settings="search"]').click()
        expect(page.locator("#search-fields")).to_be_enabled()
        page.locator("#search-provider").select_option("off")
        expect(page.locator("#search-provider-detail")).to_have_text("Web search is off.")
        page.locator('#search-settings-form button[type="submit"]').click()
        expect(page.locator("#search-feedback")).to_have_text("Settings saved.")

        page.locator('[data-settings="voice"]').click()
        page.locator("#voice-engine").select_option("browser")
        page.locator("#voice-length").fill("14")
        page.locator('#voice-settings-form button[type="submit"]').click()
        expect(page.locator("#voice-settings-status")).to_have_text("Voice settings saved.")
        page.locator("#call-language").select_option("zh")
        page.locator('#call-settings-form button[type="submit"]').click()
        expect(page.locator("#call-settings-status")).to_have_text("Call settings saved.")
        page.locator('[data-settings="appearance"]').click()
        page.locator("#look-kettle").click()
        expect(page.locator("#look-kettle")).to_have_attribute("aria-pressed", "true")
        page.locator("#avatar-enabled").uncheck()
        page.locator('.sidebar [data-view="chat"]').click()
        expect(page.locator("#chat-view")).to_be_visible()
        expect(page.locator("#avatar-header")).to_be_hidden()
        page.go_back()
        expect(page.locator('[data-settings="appearance"]')).to_be_focused()
        expect(page.locator("#avatar-enabled")).not_to_be_checked()
        page.locator("#avatar-enabled").check()
        page.locator('.sidebar [data-view="chat"]').click()
        expect(page.locator("#avatar-header .mascot")).to_have_attribute("data-look", "kettle")

        page.goto("/#settings/voice")
        expect(page.locator("#voice-engine")).to_have_value("browser")
        expect(page.locator("#voice-length")).to_have_value("14")
        expect(page.locator("#call-language")).to_have_value("zh")
