#!/usr/bin/env python3
"""Regenerate the static modulepreload links for web/index.html using Node 22."""

import argparse
from html import escape
import json
from pathlib import Path
import re
import subprocess


WEB = Path(__file__).resolve().parents[1] / "web"
BEGIN = "  <!-- BEGIN MODULEPRELOAD (generated by scripts/gen_modulepreload.py) -->\n"
END = "  <!-- END MODULEPRELOAD -->"
IMPORT_MAP = re.compile(r'<script type="importmap">(.*?)</script>', re.DOTALL)
ENTRY = re.compile(r'<script type="module" src="([^"]+)"></script>')

# Use the JavaScript parser to find static imports and re-exports without executing modules.
STATIC_GRAPH = r"""
import { readFileSync } from "node:fs";
import { SourceTextModule } from "node:vm";

const { entry, imports } = JSON.parse(readFileSync(0, "utf8"));
const origin = "https://hearth.invalid";
const queue = new Set();

function enqueue(specifier, importer) {
  const urlLike = /^(?:\/|\.\.?\/|[a-z][a-z\d+.-]*:)/i.test(specifier);
  const mapped = Object.hasOwn(imports, specifier) ? imports[specifier] : undefined;
  if (mapped === undefined && !urlLike) {
    throw new Error(`Unmapped import ${specifier} in ${importer.pathname}`);
  }
  const url = mapped === undefined ? new URL(specifier, importer) : new URL(mapped, origin);
  if (url.origin !== origin) throw new Error(`Expected a same-origin module: ${url.href}`);
  queue.add(url.href);
}

enqueue(entry, new URL(origin));
for (const href of queue) {
  const url = new URL(href);
  const source = readFileSync(`.${decodeURIComponent(url.pathname)}`, "utf8");
  const module = new SourceTextModule(source, { identifier: url.pathname });
  for (const specifier of module.dependencySpecifiers) enqueue(specifier, url);
  console.log(href.slice(origin.length));
}
"""


def render_index(web, index):
    if index.count(BEGIN) != 1 or index.count(END) != 1:
        raise ValueError("Expected one marked modulepreload block")
    before, _, block = index.partition(BEGIN)
    _, end, after = block.partition(END)
    maps = IMPORT_MAP.findall(before)
    entries = ENTRY.findall(after)
    if not end or len(maps) != 1 or len(entries) != 1:
        raise ValueError("Expected the import map, modulepreload block, and module entry in that order")
    import_map = json.loads(maps[0])
    imports = import_map["imports"]
    if import_map.get("scopes") or any(
        key.endswith("/") or key.startswith(("/", "./", "../"))
        or ":" in key or not isinstance(value, str)
        for key, value in imports.items()
    ):
        raise ValueError("Expected a flat import map with exact bare specifiers")

    result = subprocess.run(
        ["node", "--experimental-vm-modules", "--disable-warning=ExperimentalWarning",
         "--input-type=module", "-e", STATIC_GRAPH],
        cwd=web, input=json.dumps({"entry": entries[0], "imports": imports}),
        text=True, stdout=subprocess.PIPE, check=True,
    )
    links = "".join(f'  <link rel="modulepreload" href="{escape(url, quote=True)}">\n'
                    for url in result.stdout.splitlines())
    return before + BEGIN + links + END + after


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if index.html needs regeneration")
    args = parser.parse_args()
    path = WEB / "index.html"
    index = path.read_text(encoding="utf-8")
    updated = render_index(WEB, index)
    if updated == index:
        return
    if args.check:
        raise SystemExit("Stale modulepreloads. Run python scripts/gen_modulepreload.py.")
    path.write_text(updated, encoding="utf-8")


if __name__ == "__main__":
    main()
